// ── Main ──────────────────────────────────────────────────────────────────────
async function main() {
  console.log('\n' + '═'.repeat(60));
  console.log(`  ${C.bold}${C.cyan}Shonin Setup${C.reset}  — Human approval for AI agents`);
  console.log('═'.repeat(60) + '\n');
  console.log('  This wizard configures Shonin for Claude Code in ~2 minutes.\n');

  // ── Step 1: Credentials ───────────────────────────────────────────────────
  step('Step 1/4  Credentials');
  console.log('  Get your API key at https://shonin.dev\n');

  const apiKey = await ask('Shonin API key');
  if (!apiKey) { err('API key is required'); process.exit(1); }

  const approverEmail = await ask('Your email address (for approval notifications)');
  if (!approverEmail || !approverEmail.includes('@')) {
    err('A valid email address is required');
    process.exit(1);
  }

  // ── Step 2: Hook script ───────────────────────────────────────────────────
  step('Step 2/4  Hook script');
  const hookPath = path.join(os.homedir(), 'shonin-approve.sh');
  const overwrite = fs.existsSync(hookPath) ? await askYN(`${hookPath} already exists — overwrite?`, false) : true;

  if (overwrite) {
    writeFileSafe(hookPath, HOOK_SCRIPT);
    fs.chmodSync(hookPath, 0o755);
    ok(`Wrote ${hookPath}`);
  } else {
    info(`Keeping existing ${hookPath}`);
  }

  // ── Step 3: gstack AskUserQuestion hook (optional) ────────────────────────
  step('Step 3/4  gstack / AskUserQuestion routing (optional)');
  console.log('  Routes Claude\'s "AskUserQuestion" calls to your email instead of terminal.\n');

  const setupGstack = await askYN('Set up email routing for AskUserQuestion (recommended for async work)?', true);
  if (setupGstack) {
    const gstackHookPath = path.join(os.homedir(), 'shonin-decision-hook.sh');
    const overwriteGstack = fs.existsSync(gstackHookPath)
      ? await askYN(`${gstackHookPath} already exists — overwrite?`, false)
      : true;

    if (overwriteGstack) {
      writeFileSafe(gstackHookPath, GSTACK_HOOK_SCRIPT);
      fs.chmodSync(gstackHookPath, 0o755);
      ok(`Wrote ${gstackHookPath}`);
    }
  }

  // ── Step 4: Claude Code config ────────────────────────────────────────────
  step('Step 4/4  Claude Code config');

  const claudeDir = path.join(os.homedir(), '.claude');
  const claudeMdPath = path.join(claudeDir, 'CLAUDE.md');
  const settingsPath = path.join(claudeDir, 'settings.json');

  // CLAUDE.md
  if (!readFileSafe(claudeMdPath).includes('## Human Approval via Shonin')) backupFile(claudeMdPath);
  const addedClaudeMd = appendIfMissing(claudeMdPath, '## Human Approval via Shonin', CLAUDE_MD_BLOCK);
  if (addedClaudeMd) ok(`Updated ${claudeMdPath}`);

  // settings.json hooks
  backupFile(settingsPath);
  let settings = readSettings(settingsPath);
  settings = addBashHook(settings);
  if (setupGstack) settings = addAskUserQuestionHook(settings);
  writeSettings(settingsPath, settings);
  ok(`Updated ${settingsPath}`);

  // Shell env vars
  const shell = process.env.SHELL || '';
  const rcFile = shell.includes('zsh')
    ? path.join(os.homedir(), '.zshrc')
    : path.join(os.homedir(), '.bashrc');

  const envBlock = `
# Shonin — human approval for AI agents
export SHONIN_API_KEY="${apiKey}"
export SHONIN_APPROVER="${approverEmail}"
export SHONIN_API_URL="https://shonin.dev/api/v1"
# export SHONIN_SEND_DIFF=1   # also send git diffs with approval requests (your code is stored and emailed)
`;

  if (!readFileSafe(rcFile).includes('# Shonin')) backupFile(rcFile);
  const addedEnv = appendIfMissing(rcFile, '# Shonin', envBlock);
  if (addedEnv) ok(`Added env vars to ${rcFile}`);

  // ── Done ──────────────────────────────────────────────────────────────────
  console.log('\n' + '═'.repeat(60));
  console.log(`  ${C.bold}${C.green}Setup complete!${C.reset}`);
  console.log('═'.repeat(60));
  console.log(`
  ${C.bold}Next steps:${C.reset}

  1. Reload your shell:
     ${C.cyan}source ${rcFile}${C.reset}

  2. Test it:
     ${C.cyan}~/shonin-approve.sh "git push origin main" "Testing Shonin"${C.reset}

  3. You should receive an approval email at ${C.bold}${approverEmail}${C.reset}.

  ${C.dim}Restart Claude Code for the hooks to take effect.${C.reset}
`);

  rl.close();
}

main().catch((e) => {
  err(e.message || String(e));
  rl.close();
  process.exit(1);
});
